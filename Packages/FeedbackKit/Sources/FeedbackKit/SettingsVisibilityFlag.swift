    public var overrideKey: String { "flag.settingsVisibility.\(rawValue)" }

    public var parent: Self? {
        switch self {
        case .screenshotsTimestamp, .screenshotsCapturePresets: return .screenshotsAdvanced
        case .shortcutsCapture, .shortcutsClipboardPins, .shortcutsTranslation,
             .shortcutsRecording, .shortcutsHistory: return .shortcutsCustomizable
        default: break
        }
        guard let dot = rawValue.lastIndex(of: ".") else { return nil }
        return Self(rawValue: String(rawValue[..<dot]))
    }

    public var defaultState: FlagState {
        switch self {
        case .generalDiagnostics, .shortcutsSelection: .off
        default: .on
        }
    }

    /// Both channels use the same defaults. Unknown states use the default.
    public func isVisible(override: (String) -> String?) -> Bool {
        let stored = override(overrideKey).flatMap(FlagState.init(rawValue:))
        let own = stored == .on || stored == .off ? stored! : defaultState
        guard own == .on else { return false }
        return parent?.isVisible(override: override) ?? true
    }
